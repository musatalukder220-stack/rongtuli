import asyncio, sys
sys.path.insert(0, __import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), '..'))
from pw_common import *
async def main():
    async with Session() as s:
        p = s.page
        p.on('requestfailed', lambda r: print('  REQ FAILED', r.url[:80], r.failure))
        # the welcome card is not what this test is about (a sandboxed frame cannot remember it anyway)
        await p.set_content('<body style="margin:0"><iframe id="f" sandbox="allow-scripts" src="http://localhost:8000/index.html?test=1" style="border:0;width:390px;height:844px"></iframe></body>', wait_until='domcontentloaded')
        await p.wait_for_timeout(3000)
        print('frames', [(x.url[:60]) for x in p.frames])
        fr = [x for x in p.frames if x != p.main_frame][0]
        print('readyState', await fr.evaluate("document.readyState"), 'RT?', await fr.evaluate("typeof window.RT"))
        print('iframe origin', await fr.evaluate("window.origin"), 'sandboxed?', await fr.evaluate("RT.U.sandboxed()"), 'fonts', await fr.evaluate("RT.Fonts.list.length"))
        f = p.frame_locator('#f')
        await f.locator('#btn-demo').click(timeout=20000)
        await p.wait_for_timeout(600)
        await f.locator('#topbar button[title="Save picture"]').click(); await p.wait_for_timeout(1500)
        print('export sheet in sandbox:', await f.locator('.ex-info').inner_text(), '| img src starts', (await f.locator('.ex-prev').get_attribute('src'))[:22])
        print('hint:', await f.locator('.ex-hint').inner_text())
        await s.shot('70_sandbox')
        # ---- projects inside the locked-down frame: no database there, so they are kept in memory and the app says so ----
        await f.locator('.sheet-h button[title="Close"]').click(); await p.wait_for_timeout(300)
        print('storage in sandbox: persistent =', await fr.evaluate("RT.Store.ready().then(() => RT.Store.persistent)"))
        await fr.evaluate("(() => { const l = RT.Layers.text('In a frame', {x: RT.Doc.width / 2, y: RT.Doc.height / 2, size: 140}); RT.Doc.add(l); RT.History.commit(); RT.View.request(); })()")
        item = f.locator('#toolbar .tb-item[data-id="myfolders"]'); await item.scroll_into_view_if_needed(); await item.click(); await p.wait_for_timeout(300)
        await f.locator('#mf-save').click(); await p.wait_for_timeout(300)
        print('save dialog note:', await f.locator('.dlg-note').inner_text())
        await s.shot('71_sandbox_save')
        await f.locator('#btn-pj-save').click(); await p.wait_for_timeout(1500)
        print('after save: pid', bool(await fr.evaluate("RT.Doc.pid")), '| toast:', await f.locator('#toast').inner_text())
        await item.click(); await p.wait_for_timeout(300)
        await f.locator('#mf-download').click(); await p.wait_for_timeout(1200)
        print('download in sandbox -> toast:', await f.locator('#toast').inner_text())
        await f.locator('#topbar button[title="Close"]').click(); await p.wait_for_timeout(600)
        await f.locator('#btn-folders').click(); await p.wait_for_timeout(600)
        print('My folders in sandbox:', await f.locator('.pj').count(), 'card | note:', (await f.locator('.fd-note').inner_text())[:60])
        await s.shot('72_sandbox_folders')
        await f.locator('.pj-open').click(); await p.wait_for_timeout(1500)
        print('reopened in sandbox:', await fr.evaluate("RT.Doc.open && RT.Doc.layers.map(l => l.type + ':' + (l.text || '')).join(',')"))
        ok = (await fr.evaluate("RT.Doc.open && RT.Doc.layers.length === 2 && RT.Doc.layers[1].text === 'In a frame' && !RT.Store.persistent"))
        print('RESULT', 'ok' if ok else 'FAILED')
        s.report()
        if not ok: sys.exit(1)
asyncio.run(main())
